#!/usr/bin/env node
/**
 * One-shot importer: snapshots Monkeytype's themes into this repo.
 *
 *   node scripts/import-themes.ts             # latest monkeytype master
 *   node scripts/import-themes.ts --sha <sha> # a specific upstream commit
 *
 * Writes:
 *   src/themes.data.ts  palettes (+ scheme, + extra accents harvested from
 *                       upstream's per-theme stylesheets)
 *   THEMES.md           attribution + list of bundled themes
 *
 * Only color values are copied. Upstream's per-theme stylesheets target
 * Monkeytype's own DOM, so we harvest their extra colors instead of shipping
 * the CSS itself.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parseColor, rgbToOklch, distance, isDark, toHex, type OKLCH } from "../src/color.ts";
import { PALETTE_KEYS, type Palette, type ThemeRecord } from "../src/types.ts";

const REPO = "monkeytypegame/monkeytype";
const THEMES_TS = "frontend/src/ts/constants/themes.ts";
const THEME_CSS_DIR = "frontend/static/themes";
const MAX_EXTRAS = 8;

const root = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));

async function get(url: string): Promise<string> {
  const res = await fetch(url, { headers: { "user-agent": "monkeystyle-importer" } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  return res.text();
}

async function resolveSha(): Promise<string> {
  const i = process.argv.indexOf("--sha");
  if (i !== -1 && process.argv[i + 1]) return process.argv[i + 1]!;
  const json = JSON.parse(await get(`https://api.github.com/repos/${REPO}/commits/master`));
  return json.sha as string;
}

/** Parse the `themes` object literal out of upstream's TypeScript source. */
export function parseThemesSource(src: string): Record<string, Palette & { hasCss: boolean }> {
  const start = src.indexOf("export const themes");
  if (start === -1) throw new Error("Could not find `export const themes` in upstream source");
  const body = src.slice(src.indexOf("{", src.indexOf("=", start)) + 1);
  const out: Record<string, Palette & { hasCss: boolean }> = {};
  const entry = /^\s{2}(?:"([^"]+)"|([A-Za-z0-9_]+)):\s*\{([^}]*)\}/gm;
  for (const m of body.matchAll(entry)) {
    const name = m[1] ?? m[2]!;
    const fields = m[3]!;
    const record: Record<string, string> = {};
    for (const f of fields.matchAll(/(\w+):\s*"(#[0-9a-fA-F]{3,8})"/g)) {
      record[f[1]!] = f[2]!.toLowerCase();
    }
    const missing = PALETTE_KEYS.filter((k) => !record[k]);
    if (missing.length) {
      console.warn(`skip ${name}: missing ${missing.join(", ")}`);
      continue;
    }
    out[name] = {
      ...(Object.fromEntries(PALETTE_KEYS.map((k) => [k, record[k]!])) as unknown as Palette),
      hasCss: /hasCss:\s*true/.test(fields),
    };
  }
  return out;
}

/**
 * Pull distinctive, saturated colors out of an upstream theme stylesheet,
 * skipping near-duplicates of the palette and near-greys (hover mixes etc).
 */
export function harvestExtras(css: string, palette: Palette): string[] {
  const counts = new Map<string, number>();
  const re = /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b|(?:rgba?|hsla?)\([^)]*\)/g;
  for (const m of css.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(re)) {
    const rgba = parseColor(m[0]);
    if (!rgba || rgba.a < 0.5) continue;
    const hex = toHex({ ...rgba, a: 1 });
    counts.set(hex, (counts.get(hex) ?? 0) + 1);
  }
  const taken: OKLCH[] = PALETTE_KEYS.map((k) => rgbToOklch(parseColor(palette[k])!));
  const extras: string[] = [];
  for (const [hex] of [...counts].sort((a, b) => b[1] - a[1])) {
    const c = rgbToOklch(parseColor(hex)!);
    if (c.c < 0.04) continue;
    if (taken.some((t) => distance(t, c) < 0.05)) continue;
    taken.push(c);
    extras.push(hex);
    if (extras.length >= MAX_EXTRAS) break;
  }
  return extras;
}

async function main() {
  const sha = await resolveSha();
  const raw = (p: string) => `https://raw.githubusercontent.com/${REPO}/${sha}/${p}`;
  console.log(`importing ${REPO}@${sha.slice(0, 7)}`);

  const parsed = parseThemesSource(await get(raw(THEMES_TS)));
  const names = Object.keys(parsed).sort((a, b) => a.localeCompare(b));

  const records: Record<string, ThemeRecord> = {};
  for (const name of names) {
    const { hasCss, ...palette } = parsed[name]!;
    let extras: string[] = [];
    if (hasCss) {
      try {
        extras = harvestExtras(await get(raw(`${THEME_CSS_DIR}/${name}.css`)), palette);
      } catch (err) {
        console.warn(`no stylesheet for ${name}: ${(err as Error).message}`);
      }
    }
    records[name] = {
      ...palette,
      scheme: isDark(palette.bg) ? "dark" : "light",
      extras,
      hasCss,
    };
  }

  const importedAt = new Date().toISOString().slice(0, 10);
  const lines = [
    "// AUTO-GENERATED by scripts/import-themes.ts. Do not edit by hand.",
    `// Source: https://github.com/${REPO}/blob/${sha}/${THEMES_TS}`,
    "// Theme palettes by Monkeytype (Miodec) and its contributors, used with permission.",
    'import type { ThemeRecord } from "./types.ts";',
    "",
    `export const UPSTREAM = { repo: "${REPO}", sha: "${sha}", importedAt: "${importedAt}" } as const;`,
    "",
    `export type ThemeName =\n${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")};`,
    "",
    "export const themes: Record<ThemeName, ThemeRecord> = {",
    ...names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(records[n])},`),
    "};",
    "",
  ];
  await writeFile(root("src/themes.data.ts"), lines.join("\n"));

  const dark = names.filter((n) => records[n]!.scheme === "dark").length;
  const md = [
    "# Bundled themes",
    "",
    "Every palette in monkeystyle comes from [Monkeytype](https://monkeytype.com),",
    "created by Jack \"Miodec\" and designed by the Monkeytype community. Used with permission.",
    "Please go type on monkeytype.com and support the project.",
    "",
    `- Upstream: [\`${REPO}@${sha.slice(0, 7)}\`](https://github.com/${REPO}/blob/${sha}/${THEMES_TS})`,
    `- Imported: ${importedAt}`,
    `- Themes: ${names.length} (${dark} dark, ${names.length - dark} light)`,
    "",
    "Only color values are bundled. For themes that ship a custom stylesheet upstream,",
    "monkeystyle keeps the extra accent colors (`extras`) and leaves the CSS itself behind.",
    "",
    "| Theme | Scheme | bg | main | text | extras |",
    "| --- | --- | --- | --- | --- | --- |",
    ...names.map((n) => {
      const t = records[n]!;
      return `| \`${n}\` | ${t.scheme} | \`${t.bg}\` | \`${t.main}\` | \`${t.text}\` | ${t.extras.length || ""} |`;
    }),
    "",
  ];
  await writeFile(root("THEMES.md"), md.join("\n"));

  console.log(`wrote ${names.length} themes (${names.filter((n) => records[n]!.extras.length).length} with extras)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
